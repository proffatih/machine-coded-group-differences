#!/usr/bin/env python3
"""refs/refs_pa.bib: a copy of refs.bib for chicago.bst (the style Political Analysis names for
LaTeX), which ignores the doi field. Each DOI is moved into the note field as a doi.org link so
that every reference shows its DOI."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "refs", "refs.bib"), encoding="utf-8").read()


def fix(m):
    body = m.group(0)
    d = re.search(r"\bdoi\s*=\s*\{([^}]*)\}", body)
    if not d or re.search(r"\bnote\s*=", body):
        return body
    return body[:-1].rstrip().rstrip(",") + f",\n  note    = {{\\url{{https://doi.org/{d.group(1)}}}}}\n}}"


out = re.sub(r"@\w+\{[^@]*?\n\}", fix, src, flags=re.S)
open(os.path.join(ROOT, "refs", "refs_pa.bib"), "w", encoding="utf-8").write(
    "% GENERATED by code/make_pa_bib.py from refs.bib -- do not edit\n" + out)
print(len(re.findall(r"note\s*=\s*\{\\url", out)), "DOI notes")
